func TestGenerateSSHKeyPair(t *testing.T) {
	pub, priv, err := generateSSHKeyPair("foo")
	if err != nil {
		t.Fatalf("cannot generate keypair: %s\n", err)
	}

	t.Logf("Pub key:\n%s\n", pub)
	t.Logf("Priv key:\n%s\n", priv)

	priv2, err := getSSHPrivateKey(priv)
	test.NoError(t, err)
	pub2, err := getSSHPublicKey("foo", priv2)
	test.NoError(t, err)

	pubBytes, err := io.ReadAll(pub)
	test.NoError(t, err)

	pub2Bytes, err := io.ReadAll(pub2)
	test.NoError(t, err)

	assert.Equal(t, string(pubBytes), string(pub2Bytes))
}

func TestGenerateGPGKeyPair(t *testing.T) {
	k, err := GeneratePGPKeyPair("mykey", "this is a test key", "email@localhost.local")
	if err != nil {
		t.Fatalf("cannot generate keypair: %s\n", err)
	}

	stringToEncode := "I am a secret"
	entityList, err := openpgp.ReadArmoredKeyRing(bytes.NewBuffer([]byte(k.Public)))

	// encrypt string

	buf := new(bytes.Buffer)
	w, err := openpgp.Encrypt(buf, entityList, nil, nil, nil)
	if err != nil {
		t.Fatalf("cannot encrypt string: %s", err)
	}
	if _, err := w.Write([]byte(stringToEncode)); err != nil {
		t.Fatalf("cannot encrypt string: %s", err)
	}
	if err := w.Close(); err != nil {
		t.Fatalf("cannot close %s", err)
	}
	bb, err := io.ReadAll(buf)
	if err != nil {
		t.Fatalf("cannot close %s", err)
	}
	encStr := base64.StdEncoding.EncodeToString(bb)
	t.Logf("Encrypted string:\n%s\n", encStr)

	//Decrypt string

	entityPrivate, errE := openpgp.ReadArmoredKeyRing(bytes.NewBuffer([]byte(k.Private)))
	if errE != nil {
		t.Fatalf("Cannot read private key: %s\n", errE)
	}
	dec, err := base64.StdEncoding.DecodeString(encStr)
	if err != nil {
		t.Fatalf("Decode 64 %s\n", err)
	}

	md, err := openpgp.ReadMessage(bytes.NewBuffer([]byte(dec)), entityPrivate, nil, nil)
	if err != nil {
		t.Fatalf("Cannot read message %s\n", err)
	}
	btes, err := io.ReadAll(md.UnverifiedBody)
	if err != nil {
		t.Fatalf("Cannot readall %s\n", err)
	}
	decStr := string(btes)
	t.Logf("Decrypted string:\n%s\n", decStr)

	assert.Equal(t, stringToEncode, decStr)

	//Open PGP Entity
	entity, err := GetOpenPGPEntity(bytes.NewBuffer([]byte(k.Private)))
	assert.NoError(t, err)
	assert.NotNil(t, entity)

	//Regenerate public key from the private key
	pubReader, err := generatePGPPublicKey(entity)
	assert.NoError(t, err)

	pub2, _ := io.ReadAll(pubReader)
	t.Log(string(pub2))
	assert.Equal(t, string([]byte(k.Public)), string(pub2))
}

func TestGeneratePGPKeyPairOrdersRSAPrimes(t *testing.T) {
	// Without ordering, half of the keys have p > q: 10 keys make a regression near certain to show.
	for i := 0; i < 10; i++ {
		k, err := GeneratePGPKeyPair("mykey", "this is a test key", "email@localhost.local")
		test.NoError(t, err)
		entity, err := GetOpenPGPEntity(bytes.NewBufferString(k.Private))
		test.NoError(t, err)

		// The parser loads p into Primes[0] and q into Primes[1].
		for _, pk := range []*packet.PrivateKey{entity.PrivateKey, entity.Subkeys[0].PrivateKey} {
			primes := pk.PrivateKey.(*rsa.PrivateKey).Primes
			assert.Equal(t, -1, primes[0].Cmp(primes[1]), "p must be lower than q")
		}
	}
}

func TestReplacePGPKeyEmail(t *testing.T) {
	const newEmail = "robot-cds-myproj@robot.ovh.net"
	k, err := GeneratePGPKeyPair("proj-pgp-myproj", "Project Key generated by CDS", "noreply+cds-MYPROJ-proj-pgp-myproj@localhost.local")
	require.NoError(t, err)
	original, err := openpgp.ReadArmoredKeyRing(strings.NewReader(k.Public))
	require.NoError(t, err)

	updated, changed, err := ReplacePGPKeyEmail(k.Private, newEmail)
	require.NoError(t, err)
	require.True(t, changed)
	assert.Equal(t, k.KeyID, updated.KeyID)
	assert.Equal(t, k.LongKeyID, updated.LongKeyID)
	emails, err := PGPKeyEmails(k.Public)
	require.NoError(t, err)
	assert.Equal(t, []string{"noreply+cds-MYPROJ-proj-pgp-myproj@localhost.local"}, emails)
	emails, err = PGPKeyEmails(updated.Public)
	require.NoError(t, err)
	assert.Equal(t, []string{newEmail}, emails)

	for _, armored := range []string{updated.Private, updated.Public} {
		el, err := openpgp.ReadArmoredKeyRing(strings.NewReader(armored))
		require.NoError(t, err)
		require.Len(t, el, 1)
		assert.Equal(t, pgpFingerprints(original[0]), pgpFingerprints(el[0]))
		require.Len(t, el[0].Identities, 1)
		for _, id := range el[0].Identities {
			assert.Equal(t, "proj-pgp-myproj", id.UserId.Name)
			assert.Equal(t, "Project Key generated by CDS", id.UserId.Comment)
			assert.Equal(t, newEmail, id.UserId.Email)
		}
	}

	entity, err := GetOpenPGPEntity(strings.NewReader(updated.Private))
	require.NoError(t, err)
	for _, pk := range []*packet.PrivateKey{entity.PrivateKey, entity.Subkeys[0].PrivateKey} {
		primes := pk.PrivateKey.(*rsa.PrivateKey).Primes
		assert.Equal(t, -1, primes[0].Cmp(primes[1]), "p must be lower than q")
	}

	// A signature made with the rewritten private key verifies with the rewritten public key.
	const message = "signed content"
	var signature bytes.Buffer
	require.NoError(t, openpgp.ArmoredDetachSign(&signature, entity, strings.NewReader(message), nil))
	public, err := openpgp.ReadArmoredKeyRing(strings.NewReader(updated.Public))
	require.NoError(t, err)
	signer, err := openpgp.CheckArmoredDetachedSignature(public, strings.NewReader(message), &signature)
	require.NoError(t, err)
	assert.Equal(t, k.LongKeyID, signer.PrimaryKey.KeyIdString())

	_, changed, err = ReplacePGPKeyEmail(updated.Private, newEmail)
	require.NoError(t, err)
	assert.False(t, changed, "a key already holding the email must be left as is")
}

func TestReplacePGPKeyEmailRejectsInvalidEmail(t *testing.T) {
	k, err := GeneratePGPKeyPair("proj-pgp-myproj", "Project Key generated by CDS", "proj-pgp-myproj@cds")
	require.NoError(t, err)
	_, _, err = ReplacePGPKeyEmail(k.Private, "robot<cds>@robot.ovh.net")
	require.Error(t, err)
}
