const (
	testPGPKeyEmailTemplate = "robot-cds-{{lower .ProjectKey}}@robot.ovh.net"
	testPGPKeyOldEmail      = "noreply+cds@localhost.local"
)

func insertTestProjectKey(t *testing.T, db gorpmapper.SqlExecutorWithTx, projID int64, name string, keyType sdk.KeyType, email string) sdk.ProjectKey {
	var k sdk.Key
	var err error
	if keyType == sdk.KeyTypePGP {
		k, err = keys.GeneratePGPKeyPair(name, "Project Key generated by CDS", email)
	} else {
		k, err = keys.GenerateSSHKey(name)
	}
	require.NoError(t, err)
	pk := sdk.ProjectKey{Name: name, Type: keyType, ProjectID: projID, Public: k.Public, Private: k.Private, KeyID: k.KeyID, LongKeyID: k.LongKeyID}
	require.NoError(t, project.InsertKey(db, &pk))
	return pk
}

func requestAdminPGPKeysEmail(t *testing.T, api *API, jwt, method string, handler service.HandlerFunc, vars map[string]string) *httptest.ResponseRecorder {
	uri := api.Router.GetRoute(method, handler, vars)
	require.NotEmpty(t, uri)
	r := assets.NewJWTAuthentifiedRequest(t, jwt, method, uri, nil)
	rec := httptest.NewRecorder()
	api.Router.Mux.ServeHTTP(rec, r)
	return rec
}

func decodeEmailUpdateReport(t *testing.T, rec *httptest.ResponseRecorder) sdk.ProjectKeyEmailUpdateReport {
	require.Equal(t, http.StatusOK, rec.Code, rec.Body.String())
	var report sdk.ProjectKeyEmailUpdateReport
	require.NoError(t, json.Unmarshal(rec.Body.Bytes(), &report))
	return report
}

// projectKeyStatuses keeps the statuses of one project, by key name: the test database holds other projects.
func projectKeyStatuses(statuses []sdk.ProjectKeyEmailStatus, projectKey string) map[string]sdk.ProjectKeyEmailStatus {
	res := make(map[string]sdk.ProjectKeyEmailStatus)
	for _, s := range statuses {
		if s.ProjectKey == projectKey {
			res[s.KeyName] = s
		}
	}
	return res
}

func requirePGPKeyEmail(t *testing.T, db gorpmapper.SqlExecutorWithTx, original sdk.ProjectKey, email string) {
	k, err := project.LoadAndLockKeyByID(context.TODO(), db, original.ID)
	require.NoError(t, err)
	require.Equal(t, original.LongKeyID, k.LongKeyID)
	emails, err := keys.PGPKeyEmails(k.Public)
	require.NoError(t, err)
	require.Equal(t, []string{email}, emails)
	_, changed, err := keys.ReplacePGPKeyEmail(k.Private, email)
	require.NoError(t, err)
	require.False(t, changed, "the private key must hold the same email as the public one")
}

func Test_getAdminOutdatedPGPKeysEmailHandler(t *testing.T) {
	api, db, _ := newTestAPI(t)
	api.Config.Project.GPGKeyEmailAddressTemplate = testPGPKeyEmailTemplate
	_, jwtAdmin := assets.InsertAdminUser(t, db)

	proj := assets.InsertTestProject(t, db, api.Cache, sdk.RandomString(10), sdk.RandomString(10))
	expected := "robot-cds-" + strings.ToLower(proj.Key) + "@robot.ovh.net"
	defaultName := sdk.GenerateProjectDefaultKeyName(proj.Key, sdk.KeyTypePGP)
	defaultKey := insertTestProjectKey(t, db, proj.ID, defaultName, sdk.KeyTypePGP, testPGPKeyOldEmail)
	other := insertTestProjectKey(t, db, proj.ID, "proj-other", sdk.KeyTypePGP, testPGPKeyOldEmail)
	require.NoError(t, project.DisableProjectKey(db, proj.ID, other.Name))
	insertTestProjectKey(t, db, proj.ID, "proj-up-to-date", sdk.KeyTypePGP, expected)
	insertTestProjectKey(t, db, proj.ID, "proj-ssh", sdk.KeyTypeSSH, "")
	// Renaming outside the mapper leaves a signature that no longer matches the row.
	corrupted := insertTestProjectKey(t, db, proj.ID, "proj-corrupted", sdk.KeyTypePGP, testPGPKeyOldEmail)
	_, err := db.Exec("UPDATE project_key SET name = $1 WHERE id = $2", "proj-tampered", corrupted.ID)
	require.NoError(t, err)
	t.Cleanup(func() { _, _ = db.Exec("DELETE FROM project_key WHERE id = $1", corrupted.ID) })

	rec := requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodGet, api.getAdminOutdatedPGPKeysEmailHandler, nil)
	require.Equal(t, http.StatusOK, rec.Code, rec.Body.String())
	var statuses []sdk.ProjectKeyEmailStatus
	require.NoError(t, json.Unmarshal(rec.Body.Bytes(), &statuses))

	// The builtin, SSH, up to date and corrupted keys are not listed.
	require.Equal(t, map[string]sdk.ProjectKeyEmailStatus{
		defaultName: {
			ProjectKey:    proj.Key,
			KeyName:       defaultName,
			LongKeyID:     defaultKey.LongKeyID,
			Default:       true,
			Emails:        []string{testPGPKeyOldEmail},
			ExpectedEmail: expected,
		},
		other.Name: {
			ProjectKey:    proj.Key,
			KeyName:       other.Name,
			LongKeyID:     other.LongKeyID,
			Disabled:      true,
			Emails:        []string{testPGPKeyOldEmail},
			ExpectedEmail: expected,
		},
	}, projectKeyStatuses(statuses, proj.Key))
}

func Test_postAdminUpdatePGPKeysEmailHandler(t *testing.T) {
	api, db, _ := newTestAPI(t)
	api.Config.Project.GPGKeyEmailAddressTemplate = testPGPKeyEmailTemplate
	_, jwtAdmin := assets.InsertAdminUser(t, db)

	proj := assets.InsertTestProject(t, db, api.Cache, sdk.RandomString(10), sdk.RandomString(10))
	expected := "robot-cds-" + strings.ToLower(proj.Key) + "@robot.ovh.net"
	defaultKey := insertTestProjectKey(t, db, proj.ID, sdk.GenerateProjectDefaultKeyName(proj.Key, sdk.KeyTypePGP), sdk.KeyTypePGP, testPGPKeyOldEmail)
	require.NoError(t, project.DisableProjectKey(db, proj.ID, defaultKey.Name))
	other := insertTestProjectKey(t, db, proj.ID, "proj-other", sdk.KeyTypePGP, testPGPKeyOldEmail)
	projWithoutDefault := assets.InsertTestProject(t, db, api.Cache, sdk.RandomString(10), sdk.RandomString(10))
	insertTestProjectKey(t, db, projWithoutDefault.ID, "proj-other", sdk.KeyTypePGP, testPGPKeyOldEmail)

	report := decodeEmailUpdateReport(t, requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodPost, api.postAdminUpdatePGPKeysEmailHandler, nil))
	require.Contains(t, report.MissingDefaultKey, projWithoutDefault.Key)
	require.NotContains(t, report.MissingDefaultKey, proj.Key)
	require.Equal(t, map[string]sdk.ProjectKeyEmailStatus{
		defaultKey.Name: {
			ProjectKey:    proj.Key,
			KeyName:       defaultKey.Name,
			LongKeyID:     defaultKey.LongKeyID,
			Default:       true,
			Disabled:      true,
			Emails:        []string{testPGPKeyOldEmail},
			ExpectedEmail: expected,
		},
	}, projectKeyStatuses(report.Updated, proj.Key), "only the default key is updated, even disabled")
	for _, f := range report.Failed {
		require.NotEqual(t, proj.Key, f.ProjectKey, f.Error)
	}
	requirePGPKeyEmail(t, db, defaultKey, expected)
	requirePGPKeyEmail(t, db, other, testPGPKeyOldEmail)

	report = decodeEmailUpdateReport(t, requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodPost, api.postAdminUpdatePGPKeysEmailHandler, nil))
	require.Empty(t, projectKeyStatuses(report.Updated, proj.Key), "an updated key is not rewritten again")
}

func Test_postAdminUpdatePGPKeysEmailHandlerReportsFailures(t *testing.T) {
	api, db, _ := newTestAPI(t)
	// The template parses but cannot be executed: every project fails without stopping the others.
	api.Config.Project.GPGKeyEmailAddressTemplate = "{{.Unknown}}@robot.ovh.net"
	_, jwtAdmin := assets.InsertAdminUser(t, db)

	projA := assets.InsertTestProject(t, db, api.Cache, sdk.RandomString(10), sdk.RandomString(10))
	projB := assets.InsertTestProject(t, db, api.Cache, sdk.RandomString(10), sdk.RandomString(10))
	keyA := insertTestProjectKey(t, db, projA.ID, sdk.GenerateProjectDefaultKeyName(projA.Key, sdk.KeyTypePGP), sdk.KeyTypePGP, testPGPKeyOldEmail)
	keyB := insertTestProjectKey(t, db, projB.ID, sdk.GenerateProjectDefaultKeyName(projB.Key, sdk.KeyTypePGP), sdk.KeyTypePGP, testPGPKeyOldEmail)

	report := decodeEmailUpdateReport(t, requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodPost, api.postAdminUpdatePGPKeysEmailHandler, nil))
	failed := make(map[string]string)
	for _, f := range report.Failed {
		failed[f.ProjectKey] = f.KeyName
	}
	require.Equal(t, keyA.Name, failed[projA.Key])
	require.Equal(t, keyB.Name, failed[projB.Key])
	requirePGPKeyEmail(t, db, keyA, testPGPKeyOldEmail)
	requirePGPKeyEmail(t, db, keyB, testPGPKeyOldEmail)
}

func Test_postAdminUpdateProjectPGPKeyEmailHandler(t *testing.T) {
	api, db, _ := newTestAPI(t)
	api.Config.Project.GPGKeyEmailAddressTemplate = testPGPKeyEmailTemplate
	_, jwtAdmin := assets.InsertAdminUser(t, db)

	proj := assets.InsertTestProject(t, db, api.Cache, sdk.RandomString(10), sdk.RandomString(10))
	expected := "robot-cds-" + strings.ToLower(proj.Key) + "@robot.ovh.net"
	other := insertTestProjectKey(t, db, proj.ID, "proj-other", sdk.KeyTypePGP, testPGPKeyOldEmail)
	ssh := insertTestProjectKey(t, db, proj.ID, "proj-ssh", sdk.KeyTypeSSH, "")
	vars := map[string]string{"projectKey": proj.Key, "keyName": other.Name}

	report := decodeEmailUpdateReport(t, requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodPost, api.postAdminUpdateProjectPGPKeyEmailHandler, vars))
	require.Equal(t, sdk.ProjectKeyEmailUpdateReport{
		Updated: []sdk.ProjectKeyEmailStatus{{
			ProjectKey:    proj.Key,
			KeyName:       other.Name,
			LongKeyID:     other.LongKeyID,
			Emails:        []string{testPGPKeyOldEmail},
			ExpectedEmail: expected,
		}},
		Failed:            []sdk.ProjectKeyEmailUpdateFailure{},
		MissingDefaultKey: []string{},
	}, report)
	requirePGPKeyEmail(t, db, other, expected)

	report = decodeEmailUpdateReport(t, requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodPost, api.postAdminUpdateProjectPGPKeyEmailHandler, vars))
	require.Empty(t, report.Updated)
	require.Equal(t, 1, report.Skipped)

	for name, tt := range map[string]struct {
		vars map[string]string
		code int
	}{
		"unknown key":     {vars: map[string]string{"projectKey": proj.Key, "keyName": "proj-unknown"}, code: http.StatusNotFound},
		"builtin key":     {vars: map[string]string{"projectKey": proj.Key, "keyName": project.BuiltinGPGKey}, code: http.StatusNotFound},
		"unknown project": {vars: map[string]string{"projectKey": sdk.RandomString(10), "keyName": other.Name}, code: http.StatusNotFound},
		"ssh key":         {vars: map[string]string{"projectKey": proj.Key, "keyName": ssh.Name}, code: http.StatusBadRequest},
	} {
		rec := requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodPost, api.postAdminUpdateProjectPGPKeyEmailHandler, tt.vars)
		require.Equal(t, tt.code, rec.Code, "%s: %s", name, rec.Body.String())
	}
}

func Test_adminPGPKeysEmailHandlersWithoutTemplate(t *testing.T) {
	api, db, _ := newTestAPI(t)
	_, jwtAdmin := assets.InsertAdminUser(t, db)
	proj := assets.InsertTestProject(t, db, api.Cache, sdk.RandomString(10), sdk.RandomString(10))
	other := insertTestProjectKey(t, db, proj.ID, "proj-other", sdk.KeyTypePGP, testPGPKeyOldEmail)

	for name, call := range map[string]func() *httptest.ResponseRecorder{
		"list": func() *httptest.ResponseRecorder {
			return requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodGet, api.getAdminOutdatedPGPKeysEmailHandler, nil)
		},
		"update all": func() *httptest.ResponseRecorder {
			return requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodPost, api.postAdminUpdatePGPKeysEmailHandler, nil)
		},
		"update one": func() *httptest.ResponseRecorder {
			return requestAdminPGPKeysEmail(t, api, jwtAdmin, http.MethodPost, api.postAdminUpdateProjectPGPKeyEmailHandler, map[string]string{"projectKey": proj.Key, "keyName": other.Name})
		},
	} {
		rec := call()
		require.Equal(t, http.StatusBadRequest, rec.Code, "%s: %s", name, rec.Body.String())
	}
	requirePGPKeyEmail(t, db, other, testPGPKeyOldEmail)
}
